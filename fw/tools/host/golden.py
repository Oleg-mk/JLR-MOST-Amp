#!/usr/bin/env python3
"""golden.py - the bytes the selftests check the amplifier emulation against, read straight out of usb2most's firmware
(ref/usb2most/fw/main-v24.bin), so that no table in a test comes from the same head as the code it tests.

    python golden.py            write fw/main/u2m_golden.h
    python golden.py --check    exit 1 if the header is not what the firmware gives; without the firmware it says so, exit 0

Every array names the place in the binary it comes from. What they are: docs/usb2most/decode_prefacelift.md and
decode_aud3.md. What the code composes byte by byte (the level messages) is not here but in selftest.c, with the address.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent.parent
BIN = FW.parent / 'ref' / 'usb2most' / 'fw' / 'main-v24.bin'
OUT = FW / 'main' / 'u2m_golden.h'
BASE = 0x08020000
# the initial .data image: RAM address = flash address + this
DATA = 0x20005778 - 0x0804E940

# name, flash address (or RAM for .data, marked), length, what it is
FLASH = [
    ('FBLOCKS_HI', 0x0804E9FE, 8, 'NetBlock FBlockIDs, Hi-Line'),
    ('FBLOCKS_PREM', 0x0804EA06, 8, 'NetBlock FBlockIDs, Premium'),
    ('FBLOCKS_AUD3', 0x0804EC2C, 6, 'NetBlock FBlockIDs, AUD3'),
    ('FKT_HI', 0x08045AA6, 0x21, 'FktIDs 22.02, Hi-Line'),
    ('FKT_PREM', 0x08045AC7, 0x20, 'FktIDs 22.05, Premium'),
    ('FKT_2220', 0x080459CB, 0x0B, 'FktIDs 22.20'),
    ('FKT_HAMP', 0x080459C0, 0x0B, 'FktIDs 23.01, pre-facelift'),
    ('FKT_DIAG_HI', 0x08045AE7, 0x26, 'FktIDs 06.86, Hi-Line'),
    ('FKT_DIAG_PREM', 0x08045B0D, 0x26, 'FktIDs 06.86, Premium'),
    ('FKT_AUD3', 0x08047929, 0x1D, 'FktIDs 22.0A, the list with E05h'),
    ('FKT_AUD3_HAMP', 0x080477F4, 0x0E, 'FktIDs 23.01, AUD3'),
    ('FKT_AUD3_DIAG', 0x080478F5, 0x1A, 'FktIDs 06.86, AUD3'),
    ('DTC_R0', 0x08047802, 0x26, 'D19h answer to 02 AF'),
    ('DTC_R1', 0x08047828, 0x1C, 'D19h answer to 04 9D 84 13'),
    ('DTC_R2', 0x08047844, 0x15, 'D19h answer to 06 9D 84 13'),
    ('DTC_R3', 0x08047859, 0x1C, 'D19h answer to 04 F0 00 87'),
    ('DTC_R4', 0x08047875, 0x15, 'D19h answer to 06 F0 00 87'),
    ('PN_ASSEMBLY', 0x08047974, 0x1A, 'D22h answer to F1 12'),
    ('PN_HW', 0x0804798E, 0x1A, 'D22h answer to F1 91'),
    ('PN_SW', 0x080479A8, 0x1A, 'D22h answer to F1 88'),
    ('PN_CAL', 0x080479C2, 0x1A, 'D22h answer to F1 24'),
    ('GW_GET', 0x080479DC, 3, 'AUD3 at Configuration OK: F5.01 305h Get with these'),
    ('MUTE_ROWS', 0x08047946, 4 * 7, 'MuteParameters a head unit sends at start-up, rows 1..4'),
    ('EQ_HI', 0x08046728, 180, 'EqualizerSettings, Hi-Line, 45 rows of 4'),
    ('EQ_PREM', 0x080467DC, 180, 'EqualizerSettings, Premium, 45 rows of 4'),
    ('XO_PREM', 0x080468A0, 16, 'Crossover start-up table, Premium'),
    ('SL_PREM', 0x080468B8, 8, 'CrossoverSlope start-up table, Premium'),
]
RAM = [
    ('E04_INIT', 0x20005800, 4, 'E04h starting value'),
    ('E05_INIT', 0x20005804, 7, 'E05h starting value, pre-facelift'),
    ('E07_INIT', 0x2000580B, 6, 'E07h starting value'),
    ('E08_INIT', 0x20005811, 14, 'E08h starting value, pre-facelift'),
    ('LVL_INIT', 0x20005821, 20, 'SpeakerLevel rows until set, pre-facelift'),
    ('DLY_INIT', 0x200058D0, 18, 'SpeakerDelay start-up table'),
    ('AUD3_E05_INIT', 0x200059A8, 7, 'E05h starting value, AUD3'),
    ('AUD3_E08_INIT', 0x200059AF, 14, 'E08h starting value, AUD3'),
    ('AUD3_LVL_INIT', 0x200059BF, 28, 'SpeakerLevel rows until set, AUD3'),
]


def generate():
    b = BIN.read_bytes()
    out = ['/* generated by fw/tools/host/golden.py from ref/usb2most/fw/main-v24.bin: do not edit. The bytes selftest.c checks',
           '   the amplifier emulation against; what they are: docs/usb2most/decode_*.md */', '#pragma once', '#include <stdint.h>', '']

    def arr(name, addr, n, what, where):
        d = b[where - BASE:where - BASE + n]
        out.append(f'/* {what}: {addr:08X} */')
        lines = [', '.join(f'0x{v:02X}' for v in d[i:i + 16]) for i in range(0, n, 16)]
        out.append(f'static const uint8_t U2M_{name}[{n}] = {{')
        out.extend('    ' + ln + ',' for ln in lines)
        out.append('};')

    for name, addr, n, what in FLASH:
        arr(name, addr, n, what, addr)
    for name, ram, n, what in RAM:
        arr(name, ram, n, what, ram - DATA)
    return '\n'.join(out) + '\n'


def main():
    if not BIN.exists():
        # the assembled package carries the header, not usb2most's firmware: nothing to compare it with
        print(f'u2m_golden.h: not compared, no {BIN.name} here')
        return 0 if '--check' in sys.argv else 1
    text = generate()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding='ascii') == text
        print('u2m_golden.h: ' + ('as the firmware gives' if ok else 'DIFFERS from the firmware'))
        return 0 if ok else 1
    OUT.write_text(text, encoding='ascii', newline='\n')
    print(f'{OUT}: {len(text)} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
